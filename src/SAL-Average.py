    "def find_first_fire_timestep(actual_data, fire_thr=1.0, min_pixels=10):\n",
    "    \"\"\"\n",
    "    Return first timestep index where the target has at least min_pixels above fire_thr.\n",
    "    If none found, return None.\n",
    "    \"\"\"\n",
    "    for t in range(actual_data.shape[0]):\n",
    "        if np.sum(actual_data[t] > fire_thr) >= min_pixels:\n",
    "            return t\n",
    "    return None\n",
    "\n",
    "\n",
    "def find_first_valid_sal_index(sal_values, start_idx):\n",
    "    \"\"\"\n",
    "    Return first timestep >= start_idx where SAL is finite (S and A).\n",
    "    If none found, return None.\n",
    "    \"\"\"\n",
    "    for t in range(start_idx, sal_values.shape[0]):\n",
    "        s, a, l = sal_values[t]\n",
    "        if np.isfinite(s) and np.isfinite(a) and np.isfinite(l):\n",
    "            return t\n",
    "    return None\n",
    "\n",
    "\n",
    "def build_averaged_path(sal_values, start_idx, keep_first=5, avg_window=10):\n",
    "    \"\"\"\n",
    "    Create reduced SAL trajectory:\n",
    "    - keep first `keep_first` timesteps (starting at start_idx)\n",
    "    - average remaining in chunks of size avg_window (last chunk may be smaller)\n",
    "    Returns:\n",
    "      sal_path: (M,3)\n",
    "      t_path:   (M,) representative time index per point\n",
    "    \"\"\"\n",
    "    T = sal_values.shape[0]\n",
    "    if start_idx is None or start_idx >= T:\n",
    "        return np.empty((0,3)), np.array([])\n",
    "\n",
    "    # Slice from start_idx\n",
    "    sal = sal_values[start_idx:]\n",
    "\n",
    "    # Keep first points (as-is)\n",
    "    end_keep = min(keep_first, sal.shape[0])\n",
    "    kept = sal[:end_keep]\n",
    "    kept_t = np.arange(start_idx, start_idx + end_keep)\n",
    "\n",
    "    # Average remainder\n",
    "    rest = sal[end_keep:]\n",
    "    rest_start_t = start_idx + end_keep\n",
    "\n",
    "    avg_list = []\n",
    "    t_list = []\n",
    "\n",
    "    for i in range(0, rest.shape[0], avg_window):\n",
    "        chunk = rest[i:i+avg_window]  # may be < avg_window at end\n",
    "        # average ignoring NaNs\n",
    "        chunk_mean = np.nanmean(chunk, axis=0)\n",
    "        avg_list.append(chunk_mean)\n",
    "\n",
    "        # representative time = center of this chunk in original time index\n",
    "        center_t = rest_start_t + i + (len(chunk) - 1) / 2.0\n",
    "        t_list.append(center_t)\n",
    "\n",
    "    if len(avg_list) > 0:\n",
    "        avg_arr = np.vstack(avg_list)\n",
    "        t_arr = np.array(t_list)\n",
    "        sal_path = np.vstack([kept, avg_arr])\n",
    "        t_path = np.concatenate([kept_t, t_arr])\n",
    "    else:\n",
    "        sal_path = kept\n",
    "        t_path = kept_t\n",
    "\n",
    "    return sal_path, t_path"
