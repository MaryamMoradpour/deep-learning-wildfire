    "def process_dataset(model, idx, feature_file, label_file, output_dir):\n",
    "    ds_feature = xr.open_dataset(feature_file)\n",
    "    ds_label = xr.open_dataset(label_file)\n",
    "\n",
    "    try:\n",
    "        # de-normalize target\n",
    "        actual_data = de_normalize(ds_label['GRNHFX'].values.astype(np.float32),\n",
    "                                   MEAN_GRNHFX, STD_GRNHFX)\n",
    "\n",
    "        predictions = generate_predictions(model, ds_feature, MEAN_GRNHFX, STD_GRNHFX, DEVICE)\n",
    "\n",
    "        # ---- robust fire thresholding ----\n",
    "        fire_thr = 1.0        # W/m^2 (adjust if needed)\n",
    "        min_pixels = 10       # require at least 10 burning pixels\n",
    "\n",
    "        # mask non-burning areas (threshold-based)\n",
    "        zero_mask = (actual_data <= fire_thr)\n",
    "        predictions[zero_mask] = 0.0\n",
    "\n",
    "        # clean NaNs\n",
    "        predictions = np.nan_to_num(predictions, nan=0.0, posinf=0.0, neginf=0.0)\n",
    "        actual_data = np.nan_to_num(actual_data, nan=0.0, posinf=0.0, neginf=0.0)\n",
    "\n",
    "        # compute SAL\n",
    "        sal_values_95 = calculate_sal(predictions, actual_data, quantile=0.95)\n",
    "        sal_values_50 = calculate_sal(predictions, actual_data, quantile=0.5)\n",
    "\n",
    "        # find first fire timestep (based on target)\n",
    "        first_fire_t = find_first_fire_timestep(actual_data, fire_thr=fire_thr, min_pixels=min_pixels)\n",
    "        if first_fire_t is None:\n",
    "            print(f\"Dataset {idx}: No fire detected (thr={fire_thr}, min_pixels={min_pixels}). Skipping plots.\")\n",
    "            return\n",
    "\n",
    "        # find first valid SAL index (SAL may be NaN even if fire exists)\n",
    "        start_idx_95 = find_first_valid_sal_index(sal_values_95, first_fire_t)\n",
    "        start_idx_50 = find_first_valid_sal_index(sal_values_50, first_fire_t)\n",
    "\n",
    "        if start_idx_95 is None:\n",
    "            print(f\"Dataset {idx}: No valid SAL(0.95) values after fire start. Skipping Q95 plot.\")\n",
