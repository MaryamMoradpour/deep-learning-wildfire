    "    plt.ylabel(\"Predicted GRNHFX (kW/m²)\")\n",
    "    plt.title(f\"{title} (KDE Density)\")\n",
    "    plt.colorbar(scatter, label='Density')\n",
    "    plt.legend()\n",
    "    plt.tight_layout()\n",
    "    plt.savefig(os.path.join(save_path, \"kde_density_scatter.png\"))\n",
    "    plt.close()\n",
    "\n",
    "    ####################### Figure 4: 2D Histogram with Contour\n",
