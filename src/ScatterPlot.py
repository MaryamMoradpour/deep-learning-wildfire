    "def density_scatter_plot(actual_nonzero, predicted_nonzero,\n",
    "                         title=\"Actual vs Predicted GRNHFX\"):\n",
    "    \"\"\"\n",
    "    Generates four density-based scatter plots for actual vs predicted GRNHFX:\n",
    "    1. Hexbin with log scale\n",
    "    2. Hexbin with linear scale\n",
    "    3. Scatter with KDE coloring\n",
    "    4. 2D Histogram with contour\n",
    "\n",
    "    Parameters:\n",
    "    - actual_nonzero (array): Ground truth values\n",
    "    - predicted_nonzero (array): Predicted values\n",
    "    - save_path (str): Directory to save the plots\n",
    "    - title (str): Title for the plots\n",
    "    \"\"\"\n",
    "    # Remove NaNs\n",
    "    mask = ~np.isnan(actual_nonzero) & ~np.isnan(predicted_nonzero)\n",
    "    x = actual_nonzero[mask]\n",
    "    y = predicted_nonzero[mask]\n",
    "\n",
    "    ####################### Figure 1: Hexbin with log scale\n",
    "    plt.figure(figsize=(10, 8))\n",
    "    hb_log = plt.hexbin(x, y, gridsize=200, cmap='viridis', bins='log', mincnt=1)\n",
    "    plt.plot([x.min(), x.max()], [x.min(), x.max()], 'r--', label='Perfect prediction')\n",
    "    plt.xlabel('Actual GRNHFX (kW/m²)')\n",
    "    plt.ylabel('Predicted GRNHFX (kW/m²)')\n",
    "    plt.title(f\"{title} (Log Density)\")\n",
    "    plt.colorbar(hb_log, label='Log10(count)')\n",
    "    plt.legend()\n",
    "    plt.tight_layout()\n",
    "    plt.savefig(os.path.join(save_path, \"log_density_scatter.png\"))\n",
    "    plt.close()\n",
    "\n",
    "    ####################### Figure 2: Hexbin with linear scale\n",
    "    plt.figure(figsize=(10, 8))\n",
    "    hb = plt.hexbin(x, y, gridsize=200, cmap='viridis', bins=None, mincnt=1)\n",
    "    plt.plot([x.min(), x.max()], [x.min(), x.max()], 'r--', label='Perfect prediction')\n",
    "    plt.xlabel('Actual GRNHFX (kW/m²)')\n",
    "    plt.ylabel('Predicted GRNHFX (kW/m²)')\n",
    "    plt.title(f\"{title} (Count Density)\")\n",
    "    plt.colorbar(hb, label='Count')\n",
    "    plt.legend()\n",
    "    plt.tight_layout()\n",
    "    plt.savefig(os.path.join(save_path, \"count_density_scatter.png\"))\n",
    "    plt.close()\n",
